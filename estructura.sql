SET client_encoding = 'UTF8';

BEGIN;

-- Se eliminan primero las tablas hijas para que el archivo pueda repetirse sin
-- dejar objetos de una ejecucion anterior.
DROP VIEW IF EXISTS vw_ventas_limpias;
DROP TABLE IF EXISTS
    detalle_pedidos,
    pedidos,
    productos,
    clientes,
    empleados,
    sucursales,
    tipos_cliente,
    categorias,
    paises
CASCADE;

-- ------------------------------------------------------------
-- TABLAS
-- ------------------------------------------------------------
CREATE TABLE paises (
    pais_id     SERIAL PRIMARY KEY,
    codigo_pais CHAR(2)      NOT NULL UNIQUE,
    nombre_pais VARCHAR(50)  NOT NULL UNIQUE,
    continente  VARCHAR(50)  NOT NULL
);

CREATE TABLE categorias (
    categoria_id       SERIAL PRIMARY KEY,
    nombre_categoria   VARCHAR(50)  NOT NULL UNIQUE,
    descripcion        TEXT         NOT NULL
);

CREATE TABLE tipos_cliente (
    tipo_cliente_id SERIAL PRIMARY KEY,
    nombre_tipo     VARCHAR(50)  NOT NULL UNIQUE,
    descripcion     TEXT         NOT NULL
);

CREATE TABLE sucursales (
    sucursal_id        SERIAL PRIMARY KEY,
    nombre_sucursal    VARCHAR(150) NOT NULL,
    ciudad             VARCHAR(100) NOT NULL,
    pais_id            INT          NOT NULL,
    direccion_completa TEXT         NOT NULL,
    activo             BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_sucursales_paises
        FOREIGN KEY (pais_id) REFERENCES paises(pais_id)
);

CREATE TABLE empleados (
    empleado_id   SERIAL PRIMARY KEY,
    nombre        VARCHAR(30)  NOT NULL,
    apellido      VARCHAR(30)  NOT NULL,
    email         VARCHAR(100) NOT NULL UNIQUE,
    sucursal_id   INT          NOT NULL,
    fecha_ingreso DATE         NULL,
    cargo         VARCHAR(50)  NOT NULL,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_empleados_sucursales
        FOREIGN KEY (sucursal_id) REFERENCES sucursales(sucursal_id)
);

CREATE TABLE clientes (
    cliente_id       SERIAL PRIMARY KEY,
    nombre           VARCHAR(30)  NOT NULL,
    apellido         VARCHAR(30)  NOT NULL,
    email            VARCHAR(100) NOT NULL UNIQUE,
    telefono         VARCHAR(50)  NOT NULL,
    pais_id          INT          NOT NULL,
    ciudad           VARCHAR(50)  NOT NULL,
    tipo_cliente_id  INT          NOT NULL,
    fecha_registro   DATE         NULL,
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_clientes_paises
        FOREIGN KEY (pais_id) REFERENCES paises(pais_id),
    CONSTRAINT fk_clientes_tipos_cliente
        FOREIGN KEY (tipo_cliente_id) REFERENCES tipos_cliente(tipo_cliente_id)
);

CREATE TABLE productos (
    producto_id      SERIAL PRIMARY KEY,
    codigo_producto  VARCHAR(30)   NOT NULL UNIQUE,
    nombre_producto  VARCHAR(100)  NOT NULL,
    categoria_id     INT           NOT NULL,
    precio           DECIMAL(6,2)  NOT NULL,
    stock            INT           NULL,
    descripcion      TEXT          NULL,
    activo           BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_precio_positivo CHECK (precio > 0),
    CONSTRAINT chk_stock_valido    CHECK (stock >= 0),
    CONSTRAINT fk_productos_categorias
        FOREIGN KEY (categoria_id) REFERENCES categorias(categoria_id)
);

CREATE TABLE pedidos (
    pedido_id   SERIAL PRIMARY KEY,
    cliente_id  INT           NOT NULL,
    sucursal_id INT           NOT NULL,
    empleado_id INT           NULL,
    fecha_pedido TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado      VARCHAR(20)   NOT NULL DEFAULT 'En proceso',
    total       DECIMAL(10,2) NOT NULL,
    notas       TEXT          NULL,
    CONSTRAINT fk_pedidos_clientes
        FOREIGN KEY (cliente_id)  REFERENCES clientes(cliente_id),
    CONSTRAINT fk_pedidos_sucursales
        FOREIGN KEY (sucursal_id) REFERENCES sucursales(sucursal_id),
    CONSTRAINT fk_pedidos_empleados
        FOREIGN KEY (empleado_id) REFERENCES empleados(empleado_id),
    CONSTRAINT chk_estado_pedido_valido
        CHECK (estado IN ('Cancelado', 'Enviado', 'En proceso', 'Completado')),
    CONSTRAINT chk_total_pedido_valido CHECK (total > 0)
);

CREATE TABLE detalle_pedidos (
    detalle_id      SERIAL PRIMARY KEY,
    pedido_id       INT           NOT NULL,
    producto_id     INT           NOT NULL,
    cantidad        INT           NOT NULL DEFAULT 1,
    precio_unitario DECIMAL(10,2) NOT NULL,
    subtotal        DECIMAL(10,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
    CONSTRAINT chk_cantidad_valido    CHECK (cantidad > 0),
    CONSTRAINT chk_precio_unit_valido CHECK (precio_unitario > 0),
    CONSTRAINT fk_detalle_pedidos_pedidos
        FOREIGN KEY (pedido_id) REFERENCES pedidos(pedido_id),
    CONSTRAINT fk_detalle_pedidos_productos
        FOREIGN KEY (producto_id) REFERENCES productos(producto_id),
    CONSTRAINT uq_pedido_producto
        UNIQUE (pedido_id, producto_id)
);

